export const HISTORY = `The Ekuri Initiative is a Community-Based Conservation Organization that was registered with the Corporate Affairs Commission (CAC), Abuja, Nigeria, on March 13th 1997. It manages the biodiversity-rich 33,600-hectare Ekuri Community pristine rainforest Nigeria's largest communally owned and controlled pristine rainforest located at the buffer zone of the Oban Division of Cross River National Park (CRNP).

The CRNP is an internationally renowned global biodiversity hotspot and region of species endemism, home to keystone endemic species like the Cross River Gorilla (Gorilla gorilla diehli), African forest elephants (Loxodonta cyclotis), and leopards (Panthera pardus), along with other critically endangered species such as chimpanzees (Pan troglodytes ellioti), drills (Mandrillus leucophaeus), giant pangolins (Smutsia gigantea), and African buffalos (Syncerus caffer).`;

